/**
 * Builds a single-sheet .xlsx file.
 *
 * @param {{
 *   sheetName: string,
 *   rows: Array<Array<{ v: string|number|null, s?: number }>>,
 *   columnWidths?: number[],
 *   freeze?: { rows: number, cols: number },
 * }} options
 * @returns {Uint8Array}
 */
export function buildXlsx({ sheetName, rows, columnWidths = [], freeze }) {
  const encoder = new TextEncoder();
  // Excel limits sheet names to 31 chars and forbids []:*?/\
  const safeSheetName = escapeXml(String(sheetName).replace(/[[\]:*?/\\]/g, ' ').slice(0, 31) || 'Sheet1');

  const sheetRows = rows
    .map((cells, r) => {
      const xmlCells = cells
        .map((cell, c) => {
          const ref = `${columnLetter(c)}${r + 1}`;
          const style = cell?.s ? ` s="${cell.s}"` : ' s="0"';
          const value = cell?.v;
          if (value === null || value === undefined || value === '') return `<c r="${ref}"${style}/>`;
          if (typeof value === 'number' && Number.isFinite(value)) {
            return `<c r="${ref}"${style}><v>${value}</v></c>`;
          }
          return `<c r="${ref}"${style} t="inlineStr"><is><t xml:space="preserve">${escapeXml(value)}</t></is></c>`;
        })
        .join('');
      return `<row r="${r + 1}">${xmlCells}</row>`;
    })
    .join('');

  let sheetViews = '';
  if (freeze && (freeze.rows > 0 || freeze.cols > 0)) {
    const topLeft = `${columnLetter(freeze.cols)}${freeze.rows + 1}`;
    const pane =
      freeze.rows > 0 && freeze.cols > 0 ? 'bottomRight' : freeze.rows > 0 ? 'bottomLeft' : 'topRight';
    sheetViews =
      `<sheetViews><sheetView workbookViewId="0"><pane` +
      (freeze.cols > 0 ? ` xSplit="${freeze.cols}"` : '') +
      (freeze.rows > 0 ? ` ySplit="${freeze.rows}"` : '') +
      ` topLeftCell="${topLeft}" activePane="${pane}" state="frozen"/></sheetView></sheetViews>`;
  }

  const cols = columnWidths.length
    ? `<cols>${columnWidths
        .map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`)
        .join('')}</cols>`
    : '';

  const sheetXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${sheetViews}${cols}<sheetData>${sheetRows}</sheetData></worksheet>`;

  const files = {
    '[Content_Types].xml': `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
</Types>`,
    '_rels/.rels': `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>`,
    'xl/workbook.xml': `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="${safeSheetName}" sheetId="1" r:id="rId1"/></sheets>
</workbook>`,
    'xl/_rels/workbook.xml.rels': `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>`,
    'xl/styles.xml': STYLES_XML,
    'xl/worksheets/sheet1.xml': sheetXml,
  };

  return zipStore(
    Object.entries(files).map(([name, content]) => ({ name, data: encoder.encode(content) }))
  );
}
